import { makeRecord } from "../lib/record";
import { spokenIndustry } from "../lib/format";
import type { RawRecord, SourceName } from "../lib/types";

type KeeperInput = {
  id: string;
  listedName: string;
  industry: string;
  city: string;
  state: string;
  employees: number;
  founded: number;
  ownerName: string;
  publicPhone: string;
  domain: string;
  signal: string;
  email?: string;
  ownerTitle?: string;
  source?: SourceName;
};

function directFrom(phone: string): string {
  const last = Number(phone.slice(-1));
  return `${phone.slice(0, -1)}${(last + 3) % 10}`;
}

function keeper(input: KeeperInput): RawRecord {
  const [first, ...rest] = input.ownerName.split(" ");
  const last = rest.at(-1) ?? first;
  const slug = `${first}-${last}`.toLowerCase();
  return makeRecord({
    id: input.id,
    source: input.source ?? "Google Maps",
    listedName: input.listedName,
    industry: input.industry,
    city: input.city,
    state: input.state,
    employees: input.employees,
    founded: input.founded,
    ownerName: input.ownerName,
    ownerTitle: input.ownerTitle ?? "Owner",
    publicPhone: input.publicPhone,
    domain: input.domain,
    description: `${input.listedName} is an owner-operated ${spokenIndustry(input.industry)} company in ${input.city}.`,
    signal: input.signal,
    email: input.email ?? `${first}.${last}@${input.domain}`.toLowerCase(),
    directPhone: directFrom(input.publicPhone),
    linkedin: `https://www.linkedin.com/in/${slug}-demo`,
    ownerTenure: Math.min(28, Math.max(6, new Date().getFullYear() - input.founded - 3)),
  });
}

